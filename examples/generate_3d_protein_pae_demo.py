#!/usr/bin/env python3
"""Generates a multi-domain 3D protein coordinate file (.pdb) with synthetic PAE matrix & SVG QC dashboard."""

# /// script
# requires-python = ">=3.10"
# dependencies = []
# ///

import argparse
import json
import math
from pathlib import Path

AA_CYCLE = [
    "MET", "ASP", "SER", "GLY", "PRO", "LEU", "ARG", "VAL", "PHE", "GLU",
    "LYS", "ILE", "ALA", "HIS", "ASN", "CYS", "TYR", "GLN", "THR", "TRP",
]


def generate_protein_residues(n_residues: int = 56) -> list[dict]:
    """Generates a 3-region protein: disordered N-tail (1..10), beta/loop core (11..34), C-helix (35..56)."""
    residues = []
    for i in range(n_residues):
        res_seq = i + 1
        aa = AA_CYCLE[i % len(AA_CYCLE)]
        if res_seq <= 10:
            # Region 1: Intrinsically disordered N-terminal tail (pLDDT < 50)
            x = -15.0 + i * 1.25
            y = 7.0 + math.sin(i * 1.1) * 1.9
            z = -5.5 + math.cos(i * 0.85) * 1.8
            plddt = round(35.0 + i * 1.2, 2)
            domain = 1
        elif res_seq <= 34:
            # Region 2: Rigid DNA-binding core domain (pLDDT 84..97)
            t = (i - 10) * 0.44
            x = -2.2 + math.cos(t) * 5.8
            y = -2.8 + (i - 10) * 0.32
            z = math.sin(t) * 5.4
            plddt = round(89.5 + math.sin(i * 0.7) * 6.5, 2)
            domain = 2
        else:
            # Region 3: Alpha-helical oligomerization domain (3.6 residues/turn, pitch 5.4 A)
            k = i - 34
            angle = k * (2.0 * math.pi / 3.6)
            x = 5.8 + k * 1.5 * 0.35
            y = 1.8 + 2.3 * math.cos(angle)
            z = 1.2 + 2.3 * math.sin(angle)
            plddt = round(92.0 + math.cos(i * 0.5) * 4.5, 2)
            domain = 3

        residues.append({
            "res_seq": res_seq,
            "aa": aa,
            "chain": "A",
            "x": round(x, 3),
            "y": round(y, 3),
            "z": round(z, 3),
            "plddt": plddt,
            "domain": domain,
        })
    return residues


def write_pdb(residues: list[dict], out_pdb: Path) -> None:
    lines = [
        "HEADER    SYNTHETIC MULTI-DOMAIN PROTEIN          24-OCT-26   4AGY",
        "TITLE     GENERATED BY ANTIGRAVITY SCIENCE PLUGIN COOKBOOK",
    ]
    for idx, r in enumerate(residues, start=1):
        lines.append(
            f"ATOM  {idx:5d}  CA  {r['aa']:3s} {r['chain']}{r['res_seq']:4d}    "
            f"{r['x']:8.3f}{r['y']:8.3f}{r['z']:8.3f}  1.00{r['plddt']:6.2f}           C"
        )
    lines.append("END")
    out_pdb.parent.mkdir(parents=True, exist_ok=True)
    out_pdb.write_text("\n".join(lines) + "\n", encoding="utf-8")


def build_pae_matrix(residues: list[dict]) -> list[list[float]]:
    n = len(residues)
    matrix: list[list[float]] = []
    for i in range(n):
        row: list[float] = []
        for j in range(n):
            if i == j:
                row.append(0.0)
                continue
            ri, rj = residues[i], residues[j]
            if ri["plddt"] < 50.0 or rj["plddt"] < 50.0:
                err = 24.5
            elif ri["domain"] == rj["domain"]:
                err = min(6.5, 1.2 + abs(i - j) * 0.14)
            else:
                err = 13.8
            row.append(round(err, 1))
        matrix.append(row)
    return matrix


def write_svg_dashboard(residues: list[dict], pae: list[list[float]], out_svg: Path) -> None:
    """Renders a crisp dark-mode SVG chart combining per-residue pLDDT and the 2D PAE matrix."""
    n = len(residues)
    svg = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 820 340" width="820" height="340">',
        '<rect width="820" height="340" rx="16" fill="#070B19" stroke="#00E5FF" stroke-opacity="0.35"/>',
        '<text x="28" y="36" fill="#F8FAFC" font-family="sans-serif" font-size="16" font-weight="bold">'
        'Antigravity Science Plugin - AlphaFold pLDDT Profile &amp; PAE Domain Matrix</text>',
        '<text x="28" y="56" fill="#94A3B8" font-family="sans-serif" font-size="12">'
        'Generated via zero-dependency PEP 723 uv script (examples/generate_3d_protein_pae_demo.py)</text>',
        # Left Panel: pLDDT Bar Profile
        '<rect x="28" y="76" width="460" height="230" rx="10" fill="#0F172A" stroke="#1E293B"/>',
        '<text x="44" y="100" fill="#00E5FF" font-family="sans-serif" font-size="12" font-weight="bold">'
        'Per-Residue C-Alpha pLDDT Confidence (Threshold = 50.0 &amp; 70.0)</text>',
        '<line x1="44" y1="210" x2="472" y2="210" stroke="#FF7D45" stroke-dasharray="4,4" stroke-width="1"/>',
        '<line x1="44" y1="174" x2="472" y2="174" stroke="#65CBF3" stroke-dasharray="4,4" stroke-width="1"/>',
    ]

    bar_w = 420.0 / n
    for i, r in enumerate(residues):
        score = r["plddt"]
        color = "#0053D6" if score >= 90 else ("#65CBF3" if score >= 70 else ("#FFDB13" if score >= 50 else "#FF7D45"))
        h = (score / 100.0) * 180.0
        x = 46.0 + i * bar_w
        y = 292.0 - h
        svg.append(f'<rect x="{x:.1f}" y="{y:.1f}" width="{max(2.0, bar_w - 1.2):.1f}" height="{h:.1f}" fill="{color}" rx="1.5"/>')

    # Right Panel: 2D PAE Heatmap
    svg.append('<rect x="512" y="76" width="280" height="230" rx="10" fill="#0F172A" stroke="#1E293B"/>')
    svg.append('<text x="528" y="100" fill="#00E676" font-family="sans-serif" font-size="12" font-weight="bold">Predicted Aligned Error (PAE Å)</text>')

    grid_size = 182.0
    cell = grid_size / n
    ox, oy = 560.0, 112.0
    for i in range(n):
        for j in range(n):
            err = pae[i][j]
            norm = min(1.0, err / 26.0)
            red = int(8 + norm * 22)
            green = int(220 - norm * 190)
            blue = int(145 - norm * 100)
            svg.append(
                f'<rect x="{ox + j * cell:.2f}" y="{oy + i * cell:.2f}" '
                f'width="{cell + 0.35:.2f}" height="{cell + 0.35:.2f}" fill="rgb({red},{green},{blue})"/>'
            )

    svg.append("</svg>")
    out_svg.parent.mkdir(parents=True, exist_ok=True)
    out_svg.write_text("\n".join(svg) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate synthetic 3D PDB + PAE JSON + SVG QC chart.")
    parser.add_argument("--outdir", type=Path, default=Path("examples/generated_p53_demo"))
    args = parser.parse_args()

    residues = generate_protein_residues(56)
    pae = build_pae_matrix(residues)

    pdb_path = args.outdir / "synthetic_p53_multidomain.pdb"
    pae_path = args.outdir / "synthetic_p53_pae.json"
    svg_path = args.outdir / "p53_plddt_pae_dashboard.svg"

    write_pdb(residues, pdb_path)
    pae_path.write_text(json.dumps([{"predicted_aligned_error": pae}], indent=2), encoding="utf-8")
    write_svg_dashboard(residues, pae, svg_path)

    print(f"[*] Generated 3D coordinate file : {pdb_path}")
    print(f"[*] Generated PAE matrix JSON    : {pae_path}")
    print(f"[*] Generated SVG QC dashboard   : {svg_path}")


if __name__ == "__main__":
    main()
